// 分類結果のパース
export function parseClassification(text: string): DrawingClassification {
  try {
    // JSONを抽出
    const jsonMatch = text.match(/```(?:json)?\s*([\s\S]*?)```/);
    let jsonStr = text;
    if (jsonMatch) {
      jsonStr = jsonMatch[1].trim();
    } else {
      const start = text.indexOf('{');
      const end = text.lastIndexOf('}');
      if (start !== -1 && end !== -1) {
        jsonStr = text.substring(start, end + 1);
      }
    }
    const parsed = JSON.parse(jsonStr);
    return {
      図面種別: parsed.図面種別 || 'その他',
      sub_types: Array.isArray(parsed.sub_types) ? parsed.sub_types : [],
      図面名: parsed.図面名 || '',
      図面詳細種別: parsed.図面詳細種別 || '',
      縮尺: parsed.縮尺 || '',
      階数: parsed.階数 || '',
      建物用途: parsed.建物用途 || '',
      confidence: typeof parsed.confidence === 'number' ? parsed.confidence : 0.5,
    };
  } catch {
    return {
      図面種別: 'その他',
      sub_types: [],
      図面名: '',
      図面詳細種別: '',
      縮尺: '',
      階数: '',
      建物用途: '',
      confidence: 0,
    };
  }
}
